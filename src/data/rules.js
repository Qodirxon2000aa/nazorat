// Qoidalar bo'yicha foiz (0-100) va unga mos yulduz (1-5).
// 5 yulduz faqat barcha qoida bajarilganda: 0-39% → 1, 40-59% → 2, 60-79% → 3, 80-99% → 4, 100% → 5
export const calcScore = (scores) => {
  if (!scores.length) return { percent: 0, stars: 0 };
  const percent = Math.round((scores.reduce((s, v) => s + v, 0) / (scores.length * 2)) * 100);
  return { percent, stars: Math.max(1, Math.floor(percent / 20)) };
};
